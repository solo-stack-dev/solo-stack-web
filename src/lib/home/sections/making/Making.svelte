<!--
	@component
	21:00 What I make (docs/HANDOFF-HOMEPAGE.md §5.2). One continuous ink line enters from the left, draws the current
	shape in the middle and runs on to the laptop screen on the cliff, which lights up at the end. A tall track (~5.6 viewports) with a sticky
	stage; pinned scroll progress drives the morph through six states (idea → AI → code → side projects → business →
	moon). No scroll hijacking: native scrolling only, the line follows it in a rAF loop that runs only on screen.

	Geometry: every layer of the scene lives in plate pixels (2560×1440 desktop, 1080×2340 portrait) inside `.frame`,
	a box with the plate's aspect ratio scaled by `--s` to cover the stage, so the line, the blooms, and the painted laptop
	stay aligned at any viewport size. Shapes: paths.ts (generated by scripts/making-paths.mjs); runtime: morph.ts.

	Reduced motion: no pinning, no morph. The stage collapses and a static vertical sequence of the six drawings (with
	their blooms) is shown instead (CSS media query, so it is also correct before hydration).
-->
<script lang="ts">
	import { MediaQuery } from 'svelte/reactivity';
	import { m } from '#lib/paraglide/messages.js';
	import NightClock from '#lib/home/shared/NightClock.svelte';
	import { RafLoop, ScrollProgress, reducedMotion } from '#lib/home/shared/motion.svelte.ts';
	import { BLOOM_BOX, LAYOUTS, PILLARS, STATE_IDS, bloomMask, composeLine, lineAt, progressFor, stateAt, toPathData, type MakingStateId } from './morph.ts';
	// Width ladder for the blooms (rendered ~200–440 CSS px): `…&enhanced` imports are typed by the ambient
	// declaration in sections/hero/imagetools.d.ts.
	import bloomIdea from './assets/making-bloom-idea.webp?w=900;640;450;300&quality=45&enhanced';
	import bloomAi from './assets/making-bloom-ai.webp?w=900;640;450;300&quality=45&enhanced';
	import bloomCode from './assets/making-bloom-code.webp?w=900;640;450;300&quality=45&enhanced';
	import bloomPhone from './assets/making-bloom-phone.webp?w=900;640;450;300&quality=45&enhanced';
	import bloomChart from './assets/making-bloom-chart.webp?w=900;640;450;300&quality=45&enhanced';
	import bloomMoon from './assets/making-bloom-moon.webp?w=900;640;450;300&quality=45&enhanced';

	const BLOOMS: Record<MakingStateId, typeof bloomIdea> = { idea: bloomIdea, ai: bloomAi, code: bloomCode, phone: bloomPhone, chart: bloomChart, moon: bloomMoon };
	const TITLES: Record<MakingStateId, () => string> = {
		idea: m.home_making_state_idea_title,
		ai: m.home_making_state_ai_title,
		code: m.home_making_state_code_title,
		phone: m.home_making_state_phone_title,
		chart: m.home_making_state_chart_title,
		moon: m.home_making_state_moon_title
	};
	const MASKS = Object.fromEntries(STATE_IDS.map((id) => [id, bloomMask(id)])) as Record<MakingStateId, string>;
	const FIGURE_LINES = Object.fromEntries(STATE_IDS.map((id) => [id, toPathData(composeLine('figure', id))])) as Record<MakingStateId, string>;

	// Same breakpoint as the CSS below: portrait-ish viewports use the tall plate and the vertical line.
	const portrait = new MediaQuery('(max-aspect-ratio: 1/1)', false);
	const layoutId = $derived(portrait.current ? 'mobile' : 'desktop');
	const layout = $derived(LAYOUTS[layoutId]);
	const initialLine = $derived(lineAt(layoutId, 0));
	// The laptop screen in percent of the plate: its clip polygon and center (for the halo).
	const screenClip = $derived(`polygon(${layout.screen.map((p) => `${(p.x / layout.width) * 100}% ${(p.y / layout.height) * 100}%`).join(', ')})`);
	const screenX = $derived(layout.screen.reduce((sum, p) => sum + p.x, 0) / 4);
	const screenY = $derived(layout.screen.reduce((sum, p) => sum + p.y, 0) / 4);

	const progress = new ScrollProgress({ mode: 'pinned' });

	/** Index of the state the line currently rests at or is closest to (drives title, pillars, dots). */
	let active = $state(0);
	let track: HTMLElement;
	let line: SVGPathElement;
	let glow: HTMLElement;
	const blooms: HTMLDivElement[] = [];

	// Ink grain: a small noise tile generated once on the client, used as a stroke pattern over the solid line.
	let grain = $state('');
	$effect(() => {
		const size = 128;
		const canvas = document.createElement('canvas');
		canvas.width = canvas.height = size;
		const context = canvas.getContext('2d');
		if (!context) return;
		const image = context.createImageData(size, size);
		let seed = 21;
		const random = () => (seed = (seed * 16807) % 2147483647) / 2147483647;
		for (let i = 0; i < size * size; i++) {
			const speck = random();
			// mostly clear, some soft dry-brush gaps, a few dark flecks
			const alpha = speck > 0.93 ? 200 : speck > 0.7 ? 70 * random() : 0;
			image.data.set([24, 25, 27, alpha], i * 4);
		}
		context.putImageData(image, 0, 0);
		grain = canvas.toDataURL();
	});

	let shown = 0;
	let drawn = -1;
	let drawnLayout = '';
	let first = true;
	const levels = new Float32Array(STATE_IDS.length);
	const written = new Float32Array(STATE_IDS.length).fill(-1);
	let glowWritten = -1;

	const loop = new RafLoop((dt) => {
		const target = stateAt(progress.current);
		if (first) {
			shown = target;
			first = false;
		} else {
			shown += (target - shown) * (1 - Math.exp(-dt * 9));
			if (Math.abs(target - shown) < 0.001) shown = target;
		}

		if (shown !== drawn || drawnLayout !== layoutId) {
			line.setAttribute('d', lineAt(layoutId, shown));
			drawn = shown;
			drawnLayout = layoutId;
		}

		const index = Math.round(shown);
		if (index !== active) active = index;

		// Blooms grow over time once the line rests at a state, and fade with distance as soon as it morphs on.
		for (let i = 0; i < levels.length; i++) {
			const resting = Math.abs(shown - i) < 0.04 ? 1 : 0;
			levels[i] += (resting - levels[i]) * (1 - Math.exp(-dt * (resting ? 2.6 : 5)));
			if (Math.abs(resting - levels[i]) < 0.002) levels[i] = resting;
			const near = Math.max(0, 1 - Math.abs(shown - i) * 2);
			const value = Math.round(levels[i] * near * 1000) / 1000;
			if (value !== written[i]) {
				blooms[i].style.opacity = String(value);
				blooms[i].style.transform = `scale(${0.82 + 0.18 * value})`;
				written[i] = value;
			}
		}

		const screenGlow = Math.round(Math.max(0, Math.min(1, shown - 4)) * 1000) / 1000;
		if (screenGlow !== glowWritten) {
			glow.style.opacity = String(screenGlow);
			glowWritten = screenGlow;
		}
	});

	$effect(() => {
		loop.paused = reducedMotion.current;
	});

	function goTo(state: number) {
		if (reducedMotion.current) {
			document.getElementById(`making-${STATE_IDS[state]}`)?.scrollIntoView({ block: 'center' });
			return;
		}
		const range = track.offsetHeight - window.innerHeight;
		const top = window.scrollY + track.getBoundingClientRect().top + progressFor(state) * range;
		window.scrollTo({ top, behavior: 'smooth' });
	}
</script>

