// Turns the painted cinema masters (docs/art/cinema/, docs/art/mascot/mascot-cinema-sitting.png) into the optimized
// sources in ../assets/ that `@sveltejs/enhanced-img` encodes to AVIF/WebP at build time, and writes ../art.ts with
// each layer's crop and anchors (in the cropped image's px), which layout.ts places on the stage.
//
// - Landscapes: desktop downscaled to 1920 wide (native raster 1672×941), mobile 1080×2340. High quality WebP.
// - Cliff, frame, beam, mascot: cropped to their visible alpha bounding box; anchors from docs/art/*/README.md are
//   shifted by the crop offset.
//
// Run: node src/lib/home/sections/cinema/tools/optimize-art.mjs && pnpm exec oxfmt src/lib/home/sections/cinema/art.ts
// Uses `sharp` from pnpm's virtual store (it ships with @sveltejs/enhanced-img; no new dependency).
import { createRequire } from 'node:module';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../../../../../../', import.meta.url));
const sharp = createRequire(`${root}node_modules/.pnpm/node_modules/`)('sharp');
const art = (path) => `${root}docs/art/${path}`;
const out = (name) => fileURLToPath(new URL(`../assets/${name}`, import.meta.url));

/** Alpha at or below this counts as empty when cropping (invisible residue). */
const ALPHA_EMPTY = 6;
const SOURCE_QUALITY = 92;

const webp = (image) => image.webp({ quality: SOURCE_QUALITY, alphaQuality: 100, effort: 6, smartSubsample: true });

async function alphaBox(path) {
	const { data, info } = await sharp(path).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
	let [x0, y0, x1, y1] = [info.width, info.height, -1, -1];
	for (let y = 0; y < info.height; y++) {
		for (let x = 0; x < info.width; x++) {
			if (data[(y * info.width + x) * 4 + 3] <= ALPHA_EMPTY) continue;
			if (x < x0) x0 = x;
			if (x > x1) x1 = x;
			if (y < y0) y0 = y;
			if (y > y1) y1 = y;
		}
	}
	return { x: x0, y: y0, width: x1 + 1 - x0, height: y1 + 1 - y0 };
}

async function plate(source, name, width) {
	await webp(sharp(art(source)).resize({ width })).toFile(out(name));
	console.log(`${name}: ${width} wide`);
}

/** Crops a layer and returns its size plus the given anchors (master px) shifted into the crop. */
async function layer(source, name, anchors) {
	const box = await alphaBox(art(source));
	await webp(sharp(art(source)).extract({ left: box.x, top: box.y, width: box.width, height: box.height })).toFile(out(name));
	console.log(`${name}: crop`, box);
	const shifted = Object.fromEntries(Object.entries(anchors).map(([key, value]) => [key, { ...value, x: value.x - box.x, y: value.y - box.y }]));
	return { width: box.width, height: box.height, crop: { x: box.x, y: box.y }, ...shifted };
}

await plate('cinema/cinema-landscape.png', 'cinema-landscape.webp', 1920);
await plate('cinema/cinema-landscape-mobile.png', 'cinema-landscape-mobile.webp', 1080);

// Anchors from docs/art/cinema/README.md and docs/art/mascot/README.md (master px)
const layers = {
	frame: await layer('cinema/cinema-frame.png', 'cinema-frame.webp', { window: { x: 160, y: 224, width: 1680, height: 945 } }),
	cliff: await layer('cinema/cinema-cliff.png', 'cinema-cliff.webp', { laptop: { x: 1125, y: 550 }, seat: { x: 380, y: 360, width: 450, height: 270 } }),
	beam: await layer('cinema/cinema-beam.png', 'cinema-beam.webp', { origin: { x: 172, y: 1158 }, endA: { x: 1200, y: 100 }, endB: { x: 1530, y: 700 } }),
	mascot: await layer('mascot/mascot-cinema-sitting.png', 'mascot-cinema-sitting.webp', { seat: { x: 530, y: 1115 } })
};

writeFileSync(
	fileURLToPath(new URL('../art.ts', import.meta.url)),
	`// Generated by tools/optimize-art.mjs from the masters in docs/art/. Do not edit; re-run the tool instead.
// Sizes are the cropped images in px; anchors are in the cropped image's px; \`crop\` is the offset in the master.

export const ART = ${JSON.stringify(layers, null, '\t')} as const;
`
);
console.log('art.ts written');
