// Builds ../assets/mascot-game-sheet.webp and its frame table ../sprite-sheet.ts from docs/art/mascot/mascot-game-sprite-master.png.
//
// One pose as a small mip chain (LEVELS), so the canvas always downscales from the nearest larger level: crisp at
// DPR 1…3 without the shimmer of drawing a big image very small.
//
// Run: node src/lib/home/sections/game/moon-planet/tools/build-sprite.mjs
// Uses `sharp` from pnpm's virtual store (ships with @sveltejs/enhanced-img; no new dependency).
import { createRequire } from 'node:module';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../../../../../../../', import.meta.url));
const sharp = createRequire(`${root}node_modules/.pnpm/node_modules/`)('sharp');
const MASTER = `${root}docs/art/mascot/mascot-game-sprite-master.png`;
const OUT = fileURLToPath(new URL('../assets/mascot-game-sheet.webp', import.meta.url));
const TABLE = fileURLToPath(new URL('../sprite-sheet.ts', import.meta.url));

/** Figure heights of the mip levels (device px), large → small. */
const LEVELS = [256, 128, 64];
const PAD = 2;
const ALPHA_THRESHOLD = 8;

const { data, info } = await sharp(MASTER).ensureAlpha().extractChannel(3).raw().toBuffer({ resolveWithObject: true });
let x0 = info.width;
let y0 = info.height;
let x1 = -1;
let y1 = -1;
for (let y = 0; y < info.height; y++) {
	for (let x = 0; x < info.width; x++) {
		if (data[y * info.width + x] <= ALPHA_THRESHOLD) continue;
		x0 = Math.min(x0, x);
		x1 = Math.max(x1, x);
		y0 = Math.min(y0, y);
		y1 = Math.max(y1, y);
	}
}
const crop = { left: x0, top: y0, width: x1 - x0 + 1, height: y1 - y0 + 1 };

const cells = [];
let cursor = 0;
for (const height of LEVELS) {
	const width = Math.round((crop.width / crop.height) * height);
	const buffer = await sharp(MASTER).extract(crop).resize({ width, height, kernel: 'lanczos3', fit: 'fill' }).png().toBuffer();
	cells.push({ buffer, x: cursor + PAD, y: PAD, w: width, h: height });
	cursor += width + PAD * 2;
}
const sheetW = cursor;
const sheetH = LEVELS[0] + PAD * 2;
await sharp({ create: { width: sheetW, height: sheetH, channels: 4, background: { r: 0, g: 0, b: 0, alpha: 0 } } })
	.composite(cells.map((cell) => ({ input: cell.buffer, left: cell.x, top: cell.y })))
	.webp({ quality: 92, alphaQuality: 100, effort: 6, smartSubsample: true })
	.toFile(OUT);

const rows = cells.map((cell) => `\t{ x: ${cell.x}, y: ${cell.y}, w: ${cell.w}, h: ${cell.h} }`).join(',\n');
writeFileSync(
	TABLE,
	`// Generated by tools/build-sprite.mjs. Do not edit; re-run the script after replacing the master.

/** Mip levels of the painted mascot in ./assets/mascot-game-sheet.webp (sheet px), large → small. One pose, facing +x. */
export const MASCOT_SHEET_LEVELS = [
${rows}
] as const;

/** Feet anchor as a fraction of a level's box: horizontal center between the feet, bottom of the soles. */
export const MASCOT_SHEET_ANCHOR = { x: 0.5, y: 1 } as const;
`
);
console.log(`mascot-game-sheet.webp ${sheetW}×${sheetH}, crop ${crop.left},${crop.top} ${crop.width}×${crop.height}, levels ${LEVELS.join('/')}`);
